"""Versioned public content contract shared by the website and native clients.

Only explicit public fields are exported. Production paths, approval records and
credentials never belong in these documents. Files are deterministic UTF-8 JSON.
"""
from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path
import re
from urllib.parse import urlsplit, urlunsplit, parse_qsl, urlencode

from PIL import Image
from jsonschema import Draft202012Validator, FormatChecker

SCHEMA_VERSION = 1
EDITION_ID = "butler-benziger-1894-en"
CONTACT = "info@thedailybutler.com"
EDITION = {
    "id": EDITION_ID,
    "title": "Butler’s Lives of the Saints",
    "publisher": "Benziger Brothers",
    "year": 1894,
    "language": "en",
    "rights": "Public-domain text",
    "calendar_note": "Dates follow the traditional calendar of the 1894 edition.",
}


def title_case(value):
    value = re.sub(r"\bST\.?\s+", "Saint ", value, flags=re.I)
    words = value.split()
    return " ".join((w.lower() if i and w.lower() in {"of", "the", "and", "in", "on", "within"}
                     else w.title()) if w.isupper() else w for i, w in enumerate(words))


def episode_name(ep):
    return title_case(" & ".join(ep["saints"]) or ep["title"])


def encode(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"),
                       allow_nan=False) + "\n").encode("utf-8")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def revision(value):
    return dict(value, revision=digest(encode(value)))


def public_url(value, host):
    if value.startswith("/") and not value.startswith("//"):
        value = f"https://{host}{value}"
    parsed = urlsplit(value)
    if parsed.scheme != "https" or not parsed.netloc or parsed.username or parsed.password:
        raise ValueError(f"Expected a public HTTPS URL: {value!r}")
    return value


def versioned_url(value, sha):
    if not sha:
        return value
    parsed = urlsplit(value)
    query = [(k, v) for k, v in parse_qsl(parsed.query) if k != "v"]
    return urlunsplit(parsed._replace(query=urlencode(query + [("v", sha)])))


def image_record(root, relative, host):
    """Describe the exact generated bytes, never the source master or local path."""
    path = (Path(root) / relative.lstrip("/")).resolve()
    if not path.is_relative_to(Path(root).resolve() / "assets") or not path.is_file():
        raise ValueError(f"Missing generated public image: {relative}")
    data = path.read_bytes()
    sha = digest(data)
    with Image.open(path) as picture:
        width, height = picture.size
    return {"url": versioned_url(public_url(relative, host), sha), "sha256": sha,
            "bytes": len(data), "width": width, "height": height, "mime_type": "image/webp"}


def reading_id(mmdd):
    return f"{EDITION_ID}:{mmdd}"


def reader_document(days, host):
    expected = {f"{month:02d}-{day:02d}" for month, count in enumerate(
        [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31], 1) for day in range(1, count + 1)}
    if len(days) != 366 or {day["mmdd"] for day in days} != expected:
        raise ValueError("Content requires every unique day of the 366-day calendar")
    readings = []
    for day in days:
        rid = reading_id(day["mmdd"])
        entries, seen = [], {}
        for entry in day["entries"]:
            # Content anchors survive insertion/reordering of unchanged paragraphs.
            # Changed text gets a new anchor: clients must not move annotations silently.
            def block(text, kind):
                base = f"{rid}:{kind}:{digest(text.encode('utf-8'))[:24]}"
                seen[base] = seen.get(base, 0) + 1
                return {"id": f"{base}:{seen[base]}", "text": text}
            entries.append({
                "heading": entry["name"], "display_heading": title_case(entry["name"]),
                "paragraphs": [block(text, "paragraph") for text in entry["paras"]],
                "reflection": block(entry["reflection"], "reflection") if entry["reflection"] else None,
            })
        readings.append(revision({
            "id": rid, "calendar_day": day["mmdd"], "label": day["label"],
            "website_url": public_url(f"/reader/{day['mmdd']}/", host), "entries": entries,
            "reading_minutes": max(1, math.ceil(sum(len(" ".join(e["paras"]).split())
                                                     for e in day["entries"]) / 200)),
        }))
    return {"kind": "reader", "schema_version": SCHEMA_VERSION, "edition": EDITION, "readings": readings}


def catalog_document(root, episodes, host):
    items, ids, dates = [], set(), set()
    for ep in sorted(episodes, key=lambda ep: ep["date"], reverse=True):
        eid = ep["guid"]
        if not isinstance(eid, str) or not eid.strip() or eid in ids or ep["date"] in dates:
            raise ValueError("Episode IDs and dates must be nonempty and unique")
        ids.add(eid)
        dates.add(ep["date"])
        duration = ep.get("duration_s")
        size = ep.get("audio_bytes")
        if not isinstance(duration, (float, int)) or not math.isfinite(duration) or duration <= 0:
            raise ValueError(f"Missing audio duration for {eid}")
        if not isinstance(size, int) or isinstance(size, bool) or size <= 0:
            raise ValueError(f"Missing audio byte size for {eid}")
        sha = ep.get("audio_sha256")
        if sha is not None and not re.fullmatch(r"[0-9a-f]{64}", sha):
            raise ValueError(f"Invalid audio digest for {eid}")
        landscape = [image_record(root, ep["thumbnail"], host)]
        small = f"/assets/episode-{ep['date']}-small.webp"
        if ep["thumbnail"].startswith("/assets/episode-"):
            landscape.insert(0, image_record(root, small, host))
        square = [image_record(root, path, host) for path in ep["square_artwork"]]
        video = None
        if ep.get("video_id"):
            video = {"provider": "youtube", "id": ep["video_id"],
                     "url": f"https://www.youtube.com/watch?v={ep['video_id']}"}
        items.append(revision({
            "id": eid, "date": ep["date"], "reading_id": reading_id(ep["mmdd"]),
            "title": ep["title"], "display_title": episode_name(ep),
            "published_at": ep["pub_date"], "website_url": public_url(f"/episode/{ep['date']}/", host),
            "notes": ep["description"],  # Full original notes include all music credits.
            "audio": {"url": versioned_url(public_url(ep["mp3_url"], host), sha),
                      "mime_type": "audio/mpeg", "duration_seconds": duration,
                      "bytes": size, "sha256": sha},
            "video": video, "artwork": {"landscape": landscape, "square": square},
        }))
    return {"kind": "catalog", "schema_version": SCHEMA_VERSION, "episodes": items}


def write_content(root, episodes, days, host, youtube, subscriptions):
    documents = {
        "catalog": catalog_document(root, episodes, host),
        "reader": reader_document(days, host),
        "site": {"kind": "site", "schema_version": SCHEMA_VERSION, "name": "The Daily Butler",
                 "description": "A saint a day, read aloud. Complete traditional readings and reflections.",
                 "contact_email": CONTACT, "edition": EDITION,
                 "links": {"website": f"https://{host}/", "about": f"https://{host}/about/",
                           "youtube": youtube, **subscriptions}},
    }
    directory = Path(root) / "content/v1"
    directory.mkdir(parents=True, exist_ok=True)
    schema_bytes = Path(__file__).with_name("content.schema.json").read_bytes()
    validator = Draft202012Validator(json.loads(schema_bytes), format_checker=FormatChecker())
    files = {}
    for name, document in documents.items():
        validator.validate(document)
        data = encode(document)
        (directory / f"{name}.json").write_bytes(data)
        files[name] = {"url": public_url(f"/content/v1/{name}.json", host),
                       "sha256": digest(data), "bytes": len(data)}
    manifest = {"kind": "manifest", "schema_version": SCHEMA_VERSION, "content_version": digest(encode(files)),
                "episode_count": len(episodes), "reading_count": len(days), "documents": files}
    # Written last; clients validate every referenced hash before switching releases.
    validator.validate(manifest)
    (directory / "schema.json").write_bytes(schema_bytes)
    (directory / "manifest.json").write_bytes(encode(manifest))
    return manifest
